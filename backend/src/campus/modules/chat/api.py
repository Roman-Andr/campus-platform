async def create_chat(
    data: ChatInput,
    session: DbSession,
    principal: CurrentUser,
    response: Response,
) -> ChatOutput:
    """Create a personal chat, or return the existing one.

    The same pair and link always maps to one chat: a repeated creation
    answers ``200`` with the stored chat (``201`` means it was created).
    """
    chat, created = await create_personal_chat(
        session,
        creator_id=principal.user_id,
        recipient_id=data.recipient_id,
        listing_id=data.listing_id,
        interaction_id=data.interaction_id,
    )
    if not created:
        response.status_code = 200
    return (await hydrate(session, [chat]))[0]


@router.get("")
async def list_chats(
    request: Request,
    session: DbSession,
    principal: CurrentUser,
    page: PageQuery,
    order_by: Literal[
        "-updated_at", "updated_at", "-created_at", "created_at"
    ] = "-updated_at",
) -> Page[ChatOutput]:
    """List the current user's dialogs, the most recently active first."""
    query = sort_by(
        select(Chat)
        .join(ChatMember, ChatMember.chat_id == Chat.id)
        .where(
            ChatMember.user_id == principal.user_id,
            ChatMember.left_at.is_(None),
        ),
        order_by,
        {"updated_at": Chat.updated_at, "created_at": Chat.created_at},
        Chat.id,
    )
    result = await paginate(
        session,
        query,
        page,
        ChatItem,
        settings=request.app.state.settings,
        context=f"chats:{principal.user_id}",
    )
    return Page[ChatOutput](
        items=await hydrate(
            session, [await session.get_one(Chat, item.id) for item in result.items]
        ),
        next_page=result.next_page,
    )


@router.get("/search")
async def search_chats(
    request: Request,
    session: DbSession,
    principal: CurrentUser,
    page: PageQuery,
    q: Annotated[
        str,
        Query(
            description=(
                "Russian or English full-text query; blank returns no matches."
            )
        ),
    ] = "",
) -> Page[ChatSearchResult]:
    """Search messages only in dialogs of the current user.

    The GIN indexes on both partitioned parents supply the hits from active
    and archived partitions; membership is checked in SQL before a row can
    leave the database. Relevance is ordered by the combined
    Russian and English vector, then by creation time and id, so equal
    relevance still has a total, repeatable order. A cursor is bound to the
    user and the normalized query and cannot be reused for another search.
    """
    settings = request.app.state.settings
    if len(q) > settings.chat_search_query_max_length:
        raise ProblemError(
            CHAT_SEARCH_INVALID,
            max_length=settings.chat_search_query_max_length,
        )
    query = q.strip()
    if not query:
        return Page(items=[], next_page=None)
    terms = func.plainto_tsquery("russian", query).op("||")(
        func.plainto_tsquery("english", query)
    )
    rank = func.ts_rank_cd(ChatMessageHistory.search_vector, terms)
    search = (
        select(ChatMessageHistory)
        .join(ChatMember, ChatMember.chat_id == ChatMessageHistory.chat_id)
        .where(
            ChatMember.user_id == principal.user_id,
            ChatMessageHistory.deleted_at.is_(None),
            ChatMessageHistory.search_vector.op("@@")(terms),
        )
        .order_by(
            rank.desc(),
            ChatMessageHistory.created_at.desc(),
            ChatMessageHistory.id.desc(),
        )
    )
    result = await paginate(
        session,
        search,
        page,
        MessageOutput,
        settings=settings,
        context=f"chat-search:{principal.user_id}:{query}",
    )
    return Page[ChatSearchResult](
        items=await search_results(
            session,
            await hydrate_messages(session, result.items),
            query,
            settings.chat_search_snippet_length,
        ),
        next_page=result.next_page,
    )


