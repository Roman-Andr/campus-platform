@router.post(
    "/{chat_id}/messages",
    status_code=201,
    responses={
        200: {
            "model": MessageOutput,
            "description": "The message was already stored for this client UUID.",
        }
    },
)
async def send_message(  # noqa: PLR0913, PLR0917
    chat_id: UUID,
    data: MessageInput,
    request: Request,
    session: DbSession,
    principal: CurrentUser,
    response: Response,
) -> MessageOutput:
    """Store a message; the server sequence, not device time, orders it.

    A repeat of the client UUID with the same text returns the stored
    message (``200``); with different text it is ``409``. The
    ``Idempotency-Key`` repeats the whole response within its retention.
    """
    message, created = await post_message(
        session,
        chat_id=chat_id,
        sender_id=principal.user_id,
        client_id=data.client_id,
        text=data.text,
        settings=request.app.state.settings,
        reply_to_id=data.reply_to_id,
        photo_ids=data.photo_ids,
    )
    if not created:
        response.status_code = 200
    return (await hydrate_messages(session, [message_output(message)]))[0]
