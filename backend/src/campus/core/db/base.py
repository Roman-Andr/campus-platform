"""Declarative base and the base entity of all tables."""

from datetime import datetime
from typing import Any, ClassVar
from uuid import UUID

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.ext.asyncio import AsyncAttrs
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from campus.core import clock

# Deterministic constraint names, so migrations can refer to them.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_N_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(AsyncAttrs, DeclarativeBase):
    """Declarative base: one metadata for all modules, naming convention."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    # Points in time are always stored as timestamptz (specification, 5.5.1).
    type_annotation_map: ClassVar[dict[Any, Any]] = {datetime: DateTime(timezone=True)}


class Entity(Base):
    """Base of entity tables: UUIDv7 key and creation and update times.

    The key is generated by PostgreSQL 18 ``uuidv7()``, so keys are ordered
    by creation time. The times come from :mod:`campus.core.clock`, not from
    the database clock, so tests control them.
    """

    __abstract__ = True

    id: Mapped[UUID] = mapped_column(primary_key=True, server_default=func.uuidv7())
    created_at: Mapped[datetime] = mapped_column(default=clock.now)
    updated_at: Mapped[datetime] = mapped_column(default=clock.now, onupdate=clock.now)
