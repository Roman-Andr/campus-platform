import '../../../core/api/generated/campus_api.dart';

/// State of a message that is still in the device outbox.
enum OutgoingChatState { pending, failed }

/// Why an outgoing message has not been stored by the server yet.
///
/// The code is kept instead of a server message: the interface translates
/// it, so an error is never shown as technical text of the server.
enum OutgoingChatFailure {
  network,
  rateLimited,
  forbidden,
  notFound,
  conflict,
  invalid,
  unauthorized,
  server,
  photo,
  unexpected,
}

/// The visible part of a quoted message.
///
/// The server returns the current text of a quoted message, never a hidden
/// revision; a deleted quote arrives as a null payload with a non-null id.
class ChatQuote {
  const ChatQuote({
    required this.messageId,
    required this.senderId,
    required this.text,
    required this.createdAt,
  });

  final String messageId;
  final String senderId;
  final String text;
  final DateTime createdAt;

  factory ChatQuote.fromJson(Map<String, Object?> json) => ChatQuote(
    messageId: json['id'] as String,
    senderId: json['sender_id'] as String,
    text: json['text'] as String,
    createdAt: DateTime.parse(json['created_at'] as String).toUtc(),
  );

  Map<String, Object?> toJson() => {
    'id': messageId,
    'sender_id': senderId,
    'text': text,
    'created_at': createdAt.toUtc().toIso8601String(),
  };
}

/// The quote snapshot of [message]; null when it quotes nothing or when the
/// quoted message is already deleted and the server returned no visible part.
ChatQuote? quoteOf(MessageOutput message) {
  final reply = message.replyTo;
  return reply is QuoteOutput
      ? ChatQuote(
          messageId: reply.id,
          senderId: reply.senderId,
          text: reply.text,
          createdAt: reply.createdAt,
        )
      : null;
}

/// The quote another message would show when it quotes [message].
///
/// It uses only the visible row returned by the API, so a hidden revision
/// can never become a quote.
ChatQuote chatQuoteOf(MessageOutput message) => ChatQuote(
  messageId: message.id,
  senderId: message.senderId,
  text: message.text,
  createdAt: message.createdAt,
);

/// A message waiting in the persistent outbox of this account.
class OutgoingChatMessage {
  const OutgoingChatMessage({
    required this.chatId,
    required this.clientId,
    required this.idempotencyKey,
    required this.text,
    required this.createdAt,
    required this.attempts,
    required this.state,
    this.replyToId,
    this.replyTo,
    this.photoIds = const [],
    this.failure,
  });

  final String chatId;

  /// UUIDv7 generated by the device; it never changes between retries.
  final String clientId;

  /// UUIDv7 of the whole operation; every repeat sends the same key.
  final String idempotencyKey;

  final String text;

  /// The immutable `reply_to_id` sent with every retry.
  ///
  /// It is kept apart from [replyTo]: the visible quote snapshot may be
  /// refreshed or cleared when the quoted message is edited or deleted, but
  /// the wire field must not change after the first attempt, or a retry with
  /// the same Idempotency-Key would send different content.
  final String? replyToId;

  /// The visible quote used by the pending bubble; null means the quoted
  /// message was deleted.
  final ChatQuote? replyTo;

  /// Ready photo ids chosen before the first attempt.
  final List<String> photoIds;

  /// When the user sent the message, in UTC.
  final DateTime createdAt;

  final int attempts;

  final OutgoingChatState state;

  /// The last classified failure; null while the message is only waiting.
  final OutgoingChatFailure? failure;

  String get localId => '$chatId/$clientId';
}

/// One row of the open dialog: either delivered by the server or still in
/// the outbox.
class ChatThreadItem {
  const ChatThreadItem({
    required this.clientId,
    required this.senderId,
    required this.text,
    required this.createdAt,
    this.id,
    this.sequence,
    this.version = 1,
    this.replyToId,
    this.replyTo,
    this.photoIds = const [],
    this.outgoing,
  });

  /// Server id; null for a message that is still in the outbox.
  final String? id;

  final String clientId;
  final String senderId;
  final String text;

  /// Server creation time for a delivered message, local send time for a
  /// pending one.
  final DateTime createdAt;

  /// The authoritative server order number; null for a pending message.
  final int? sequence;

  /// Server revision of the text; edits do not take a new sequence.
  final int version;

  final String? replyToId;

  /// Current visible quote snapshot, when the quoted message is available.
  final ChatQuote? replyTo;

  final List<String> photoIds;

  /// The outbox row when the message has not been delivered yet.
  final OutgoingChatMessage? outgoing;

  bool get isPending => outgoing != null;

  /// The server marks every edit with a higher version.
  bool get edited => !isPending && version > 1;
}

/// Combines delivered history and the outbox into the order shown by a chat.
///
/// Delivered messages are ordered by the server sequence, never by a device
/// clock. Pending messages have no sequence yet and follow the delivered
/// ones in local send order; a message that the server already stored is
/// dropped from the outbox copy by its client UUID.
List<ChatThreadItem> chatThread({
  required Iterable<MessageOutput> delivered,
  required Iterable<OutgoingChatMessage> outgoing,
  required String myId,
}) {
  final stored = delivered.toList()
    ..sort((a, b) => a.sequence.compareTo(b.sequence));
  final storedClients = {for (final message in stored) message.clientId};
  final pending =
      outgoing
          .where((message) => !storedClients.contains(message.clientId))
          .toList()
        ..sort((a, b) {
          final byTime = a.createdAt.compareTo(b.createdAt);
          return byTime != 0 ? byTime : a.clientId.compareTo(b.clientId);
        });
  return [
    for (final message in stored)
      ChatThreadItem(
        id: message.id,
        clientId: message.clientId,
        senderId: message.senderId,
        text: message.text,
        createdAt: message.createdAt,
        sequence: message.sequence,
        version: message.version,
        replyToId: message.replyToId,
        replyTo: quoteOf(message),
        photoIds: message.photoIds ?? const [],
      ),
    for (final message in pending)
      ChatThreadItem(
        clientId: message.clientId,
        senderId: myId,
        text: message.text,
        createdAt: message.createdAt,
        replyTo: message.replyTo,
        replyToId: message.replyToId,
        photoIds: message.photoIds,
        outgoing: message,
      ),
  ];
}

/// The participant of [chat] other than [myId], if the API returned both.
ParticipantOutput? otherParticipant(ChatOutput chat, String? myId) {
  for (final participant in chat.participants) {
    if (participant.id != myId) return participant;
  }
  return chat.participants.isEmpty ? null : chat.participants.first;
}

/// Full name of a chat participant.
String participantName(ParticipantOutput participant) =>
    '${participant.firstName} ${participant.lastName}'.trim();

/// The last message of a dialog list row; null for a dialog without messages.
MessageOutput? lastMessageOf(ChatOutput chat) {
  final message = chat.lastMessage;
  return message is MessageOutput ? message : null;
}

/// Merges server pages without repeats, ordered by the server sequence.
List<MessageOutput> mergeMessages(
  Iterable<MessageOutput> current,
  Iterable<MessageOutput> next,
) {
  final byClient = <String, MessageOutput>{};
  for (final message in [...current, ...next]) {
    byClient[message.clientId] = message;
  }
  return byClient.values.toList()
    ..sort((a, b) => a.sequence.compareTo(b.sequence));
}
