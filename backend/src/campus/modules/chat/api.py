router = api_router(
    prefix="/chats",
    tags=["Chats"],
    responses={
        404: {"model": Problem},
        409: {"model": Problem},
        429: {"model": Problem},
    },
)


class ParticipantOutput(BaseModel):
    id: UUID
    first_name: str
    last_name: str
    account_type: str


class MessageOutput(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: UUID
    chat_id: UUID
    sender_id: UUID
    client_id: UUID = Field(description="Message UUID generated by the device.")
    sequence: int = Field(
        description="Server order number inside the chat; authoritative order."
    )
    text: str
    created_at: Instant


class ChatItem(BaseModel):
    """A chat row before participants and the last message are attached."""

    model_config = ConfigDict(from_attributes=True)
    id: UUID
    kind: str
    listing_id: UUID | None
    interaction_id: UUID | None
    created_at: Instant
    updated_at: Instant


class ChatOutput(BaseModel):
    id: UUID
    kind: str
    listing_id: UUID | None
    interaction_id: UUID | None
    created_at: Instant
    updated_at: Instant
    participants: list[ParticipantOutput]
    last_message: MessageOutput | None = None


class ChatInput(BaseModel):
    model_config = ConfigDict(extra="forbid")
    recipient_id: UUID = Field(description="The other member of the chat.")
    listing_id: UUID | None = Field(
        default=None, description="Listing the dialog is about, if any."
    )
    interaction_id: UUID | None = Field(
        default=None,
        description=(
            "Interaction the dialog is about. Its listing is stored too and"
            " both members must take part in the interaction."
        ),
    )


class MessageInput(BaseModel):
    model_config = ConfigDict(extra="forbid")
    client_id: UUID = Field(
        description=(
            "UUIDv7 generated by the device; the same identifier with the"
            " same text is stored once, even after the Idempotency-Key expires."
        )
    )
    text: str = Field(min_length=1, description="Message text.")


def message_output(message: ChatMessage) -> MessageOutput:
    return MessageOutput.model_validate(message, from_attributes=True)


def chat_output(
    chat: Chat,
    participants: list[ParticipantOutput],
    last_message: ChatMessage | None,
) -> ChatOutput:
    return ChatOutput(
        id=chat.id,
        kind=chat.kind,
        listing_id=chat.listing_id,
        interaction_id=chat.interaction_id,
        created_at=chat.created_at,
        updated_at=chat.updated_at,
        participants=participants,
        last_message=None if last_message is None else message_output(last_message),
    )


async def hydrate(session: AsyncSession, chats: list[Chat]) -> list[ChatOutput]:
    """Attach participants and the last message to ``chats`` with two queries."""
    if not chats:
        return []
    ids = [chat.id for chat in chats]
    members: dict[UUID, list[ParticipantOutput]] = defaultdict(list)
    rows = await session.execute(
        select(ChatMember.chat_id, User)
        .join(User, User.id == ChatMember.user_id)
        .where(ChatMember.chat_id.in_(ids))
        .order_by(ChatMember.chat_id, ChatMember.joined_at, ChatMember.user_id)
    )
    for chat_id, user in rows:
        members[chat_id].append(
            ParticipantOutput.model_validate(user, from_attributes=True)
        )
    last: list[ChatMessage] = list(
        await session.scalars(
            select(ChatMessage)
            .where(ChatMessage.chat_id.in_(ids))
            .order_by(ChatMessage.chat_id, ChatMessage.sequence.desc())
            .ext(distinct_on(ChatMessage.chat_id))
        )
    )
    latest = {message.chat_id: message for message in last}
    return [
        chat_output(chat, members.get(chat.id, []), latest.get(chat.id))
        for chat in chats
    ]


@router.post(
    "",
    status_code=201,
    responses={
        200: {
            "model": ChatOutput,
            "description": "The chat already exists for this pair and link.",
        }
    },
)
async def create_chat(
    data: ChatInput,
    session: DbSession,
    principal: CurrentUser,
    response: Response,
) -> ChatOutput:
    """Create a personal chat, or return the existing one.

    The same pair and link always maps to one chat: a repeated creation
    answers ``200`` with the stored chat (``201`` means it was created).
    """
    chat, created = await create_personal_chat(
        session,
        creator_id=principal.user_id,
        recipient_id=data.recipient_id,
        listing_id=data.listing_id,
        interaction_id=data.interaction_id,
    )
    if not created:
        response.status_code = 200
    return (await hydrate(session, [chat]))[0]


@router.get("")
async def list_chats(
    request: Request,
    session: DbSession,
    principal: CurrentUser,
    page: PageQuery,
    order_by: Literal[
        "-updated_at", "updated_at", "-created_at", "created_at"
    ] = "-updated_at",
) -> Page[ChatOutput]:
    """List the current user's dialogs, the most recently active first."""
    query = sort_by(
        select(Chat)
        .join(ChatMember, ChatMember.chat_id == Chat.id)
        .where(ChatMember.user_id == principal.user_id),
        order_by,
        {"updated_at": Chat.updated_at, "created_at": Chat.created_at},
        Chat.id,
    )
    result = await paginate(
        session,
        query,
        page,
        ChatItem,
        settings=request.app.state.settings,
        context=f"chats:{principal.user_id}",
    )
    return Page[ChatOutput](
        items=await hydrate(
            session, [await session.get_one(Chat, item.id) for item in result.items]
        ),
        next_page=result.next_page,
    )


@router.get("/{chat_id}")
async def read_chat(
    chat_id: UUID, session: DbSession, principal: CurrentUser
) -> ChatOutput:
    """One dialog of the current user; somebody else's chat is ``404``."""
    chat = await require_membership(session, chat_id, principal.user_id)
    return (await hydrate(session, [chat]))[0]


@router.get("/{chat_id}/messages")
async def list_messages(  # noqa: PLR0913, PLR0917
    chat_id: UUID,
    request: Request,
    session: DbSession,
    principal: CurrentUser,
    page: PageQuery,
    after_sequence: Annotated[int, Query(ge=0)] = 0,
    ascending: bool = False,
) -> Page[MessageOutput]:
    """History by server sequence; recover gaps with ascending and after_sequence.

    The cursor is the sequence of the last row seen, never an offset, so a
    page neither skips nor repeats messages when new ones arrive.
    """
    await require_membership(session, chat_id, principal.user_id)
    query = select(ChatMessage).where(
        ChatMessage.chat_id == chat_id,
        ChatMessage.sequence > after_sequence,
    )
    query = sort_by(
        query,
        "sequence" if ascending else "-sequence",
        {"sequence": ChatMessage.sequence},
        ChatMessage.id,
    )
    return await paginate(
        session,
        query,
        page,
        MessageOutput,
        settings=request.app.state.settings,
        context=f"chat:{chat_id}:{after_sequence}:{ascending}",
    )


@router.post(
    "/{chat_id}/messages",
    status_code=201,
    responses={
        200: {
            "model": MessageOutput,
            "description": "The message was already stored for this client UUID.",
        }
    },
)
async def send_message(  # noqa: PLR0913, PLR0917
    chat_id: UUID,
    data: MessageInput,
    request: Request,
    session: DbSession,
    principal: CurrentUser,
    response: Response,
) -> MessageOutput:
    """Store a message; the server sequence, not device time, orders it.

    A repeat of the client UUID with the same text returns the stored
    message (``200``); with different text it is ``409``. The
    ``Idempotency-Key`` repeats the whole response within its retention.
    """
    message, created = await post_message(
        session,
        chat_id=chat_id,
        sender_id=principal.user_id,
        client_id=data.client_id,
        text=data.text,
        settings=request.app.state.settings,
    )
    if not created:
        response.status_code = 200
    return message_output(message)
