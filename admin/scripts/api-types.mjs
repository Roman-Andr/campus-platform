import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import prettier from 'prettier';

// Build the real app schema without starting a server or its lifespan.
const backend = fileURLToPath(new URL('../../backend/', import.meta.url));
const schema = execFileSync(
  'uv',
  [
    'run',
    '--frozen',
    'python',
    '-c',
    'import json; from campus.api.app import create_app; from campus.core.config import Settings; print(json.dumps(create_app(Settings(_env_file=None, database_url=None)).openapi()))',
  ],
  { cwd: backend, encoding: 'utf8' },
);
const types =
  '// Generated by npm run api:generate. Do not edit.\n' +
  astToString(await openapiTS(JSON.parse(schema)));
const output = new URL('../src/api/schema.ts', import.meta.url);
const formatted = await prettier.format(types, {
  ...(await prettier.resolveConfig(fileURLToPath(output))),
  parser: 'typescript',
});
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== formatted) {
    throw new Error('API types are stale. Run npm run api:generate in admin/.');
  }
} else {
  await writeFile(output, formatted);
}
